import { readFile } from 'node:fs/promises'
import assert from 'node:assert/strict'
const { PGlite } = await import(process.env.PGLITE_MODULE || '@electric-sql/pglite')
const db = new PGlite()
await db.exec(await readFile(new URL('./core-reliability-fixture.sql', import.meta.url), 'utf8'))
await db.exec(await readFile(new URL('../../supabase/migrations/20260914141750_core_reliability.sql', import.meta.url), 'utf8'))
await db.exec(await readFile(new URL('../../supabase/migrations/20260914150213_booking_access_cutover.sql', import.meta.url), 'utf8'))
const uid='00000000-0000-0000-0000-000000000001', cid='00000000-0000-0000-0000-000000000002', tid='00000000-0000-0000-0000-000000000003', pass='00000000-0000-0000-0000-000000000004'
await db.query('INSERT INTO profiles VALUES ($1)',[uid])
await db.query('INSERT INTO courses(id) VALUES ($1)',[cid])
await db.query("INSERT INTO memberships(user_id,tier,status) VALUES ($1,'eagle','active')",[uid])
await db.query("INSERT INTO tee_times(id,course_id,scheduled_at) VALUES ($1,$2,now()+interval '10 days')",[tid,cid])
await db.query("INSERT INTO guest_passes(id,user_id,expires_at) VALUES ($1,$2,now()+interval '1 year')",[pass,uid])
await db.query("INSERT INTO member_credits(user_id,type,amount_cents,status,expires_at) VALUES ($1,'monthly',1000,'available',now()+interval '1 year')",[uid])
const quote={user_id:uid,course_id:cid,tee_time_id:tid,players:2,tier:'eagle',green_fee_cents:10000,platform_fee_cents:0,total_charged_cents:8000,discount_cents:1500,points_awarded:120,cart_selected:false,cart_fee_cents:0,guest_pass_id:pass,rain_check_id:null,redemption_type:null,points_redeemed:0,credits_redeemed_cents:500,join_existing_group:false,status:'confirmed'}
await db.exec('SET ROLE service_role')
const create = q => db.query('SELECT create_member_booking($1::jsonb) AS id',[JSON.stringify(q)])
await create(quote)
assert.equal((await db.query('SELECT count(*)::int AS n FROM bookings')).rows[0].n,1)
assert.equal((await db.query("SELECT amount_cents FROM member_credits WHERE status='available'")).rows[0].amount_cents,500,'partial credit must preserve unused value')
assert.equal((await db.query('SELECT available_players FROM tee_times')).rows[0].available_players,2)
await assert.rejects(create(quote),/Guest pass already used/)
assert.equal((await db.query('SELECT count(*)::int AS n FROM bookings')).rows[0].n,1,'failed pass claim rolls back booking')
assert.equal((await db.query("SELECT amount_cents FROM member_credits WHERE status='available'")).rows[0].amount_cents,500,'failed booking preserves balance')
await assert.rejects(create({...quote,guest_pass_id:null,credits_redeemed_cents:501}),/Insufficient credits/)
const online={...quote,guest_pass_id:null,credits_redeemed_cents:0,status:'pending_payment',total_charged_cents:10000,discount_cents:0,join_existing_group:true}
const {rows:[{id:bid}]}=await create(online)
assert.equal((await db.query('SELECT available_players FROM tee_times')).rows[0].available_players,0)
await assert.rejects(create(online),/Tee time unavailable|capacity exceeded/)
await db.query("UPDATE bookings SET stripe_payment_intent_id='pi_test' WHERE id=$1",[bid])
await assert.rejects(db.query("SELECT settle_booking_payment($1,'pi_test','ch_test',9999)",[bid]),/Payment does not match/)
const settle=()=>db.query("SELECT settle_booking_payment($1,'pi_test','ch_test',10000) AS settled",[bid])
assert.equal((await settle()).rows[0].settled,true)
assert.equal((await settle()).rows[0].settled,false,'payment replay must be idempotent')
assert.equal((await db.query('SELECT available_players FROM tee_times')).rows[0].available_players,0)
assert.equal((await db.query('SELECT count(*)::int AS n FROM fairway_points WHERE amount>0')).rows[0].n,0,'award points on round completion only')
await db.exec('RESET ROLE; SET ROLE authenticated')
await assert.rejects(create(quote),/permission denied/)
await assert.rejects(db.query('SELECT * FROM tee_time_occupancy'),/permission denied/)
await assert.rejects(db.query('UPDATE bookings SET total_paid=0 WHERE id=$1',[bid]),/authorized server action/)
const publicRows=await db.query('SELECT * FROM get_public_tee_time_occupancy($1,now(),now()+interval \'20 days\')',[cid])
assert.equal(publicRows.rows[0].spots_remaining,0)
assert.equal('user_id' in publicRows.rows[0],false)
assert.equal('booking_ids' in publicRows.rows[0],false)
await db.close()
console.log('PASS: migration applies; atomic booking/credit rollback; capacity; payment replay; no premature points; restricted RPC and safe public occupancy')
